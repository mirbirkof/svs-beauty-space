import { chromium } from 'playwright';
import fs from 'fs';
const TOKEN = process.env.TK;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport:{width:1280,height:900} });
const p = await ctx.newPage();
const errs=[]; p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.goto('http://127.0.0.1:3011/admin/index.html');
await p.evaluate(t=>localStorage.setItem('svs_admin_token',t), TOKEN);
await p.goto('http://127.0.0.1:3011/admin/index.html#journal');
await p.waitForTimeout(6000);
await p.screenshot({path:'/tmp/j161-journal.png',fullPage:false});
const cash = await p.evaluate(()=>{const e=document.getElementById('jCashGauge');return e?e.innerText:'(нет блока)'});
console.log('=== КАСА ЗА ДЕНЬ ===\n'+cash);
// список колонок журнала
const cols = await p.evaluate(()=>[...document.querySelectorAll('.jcol-head,.j-master,.jm-name,[class*=master]')].slice(0,40).map(e=>e.className+' :: '+e.innerText.replace(/\n/g,' | ').slice(0,80)));
console.log('=== КОЛОНКИ ===\n'+cols.join('\n'));
console.log('=== Аліна в тексте страницы ===', (await p.evaluate(()=>document.body.innerText.split('\n').filter(l=>/лін|лин|Евел/i.test(l)).slice(0,30))).join(' // '));
await p.goto('http://127.0.0.1:3011/admin/index.html#schedule');
await p.waitForTimeout(6000);
await p.screenshot({path:'/tmp/j161-sched.png',fullPage:true});
const names = await p.evaluate(()=>[...document.querySelectorAll('.smc-name')].map(e=>e.innerText.replace(/\n/g,' · ')).filter(Boolean));
console.log('=== ГРАФІК рядки ===\n'+names.join('\n'));
console.log('ERR:', errs.slice(0,10).join(' | '));
await b.close();
