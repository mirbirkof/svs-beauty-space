-- 283: Идемпотентность счетов подписки по периоду (SaaS-аудит 27.07)
--
-- ПРОБЛЕМА: generateInvoice не защищён от повторного выставления счёта за ТОТ ЖЕ период.
-- Идемпотентность держалась только на порядке операций + in-process флаге _billingRunning.
-- При мульти-инстансном деплое ИЛИ краше между сдвигом периода и вставкой счёта — возможен
-- двойной счёт (двойное списание) или пропуск. Для одного инстанса риск низкий, но перед
-- масштабированием на много салонов это прямая денежная ошибка.
--
-- РЕШЕНИЕ: частичный уникальный индекс — у подписки не может быть двух ЖИВЫХ счетов
-- (open/paid) за один и тот же период. cancelled/void не мешают (можно перевыставить).
-- Проверено перед миграцией: дублей за период = 0, индекс встаёт чисто.
-- Код (lib/billing.js) дополнительно проверяет существующий счёт ПЕРЕД вставкой и
-- возвращает его (idempotent) — DB-индекс это второй, жёсткий слой на случай гонки.

CREATE UNIQUE INDEX IF NOT EXISTS uq_invoices_saas_sub_period_live
  ON invoices_saas (subscription_id, period_start)
  WHERE status IN ('open', 'paid') AND period_start IS NOT NULL;
