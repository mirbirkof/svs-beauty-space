-- 293_order_items_stock_taken.sql — сколько товара РЕАЛЬНО списано со склада при оплате заказа.
--
-- ПРИЧИНА (найдено аудитом 12.08): списание защищено от ухода в минус (GREATEST(0,...)),
-- а возврат прибавлял полное количество позиции → если товара на остатке не было,
-- возврат СОЗДАВАЛ товар из воздуха и тихо завышал склад.
-- Журнала движений для различения мало: при нулевом списании записи просто нет,
-- и её отсутствие неотличимо от старого заказа. Поэтому храним факт явно.
--
-- NULL = заказ оплачен до этой миграции → поведение как раньше (возврат по позиции).

ALTER TABLE order_items ADD COLUMN IF NOT EXISTS stock_taken_qty NUMERIC(12,3);
COMMENT ON COLUMN order_items.stock_taken_qty IS
  'Фактически списано со склада салона при оплате. NULL = заказ до 12.08.2026 (возврат по qty).';
