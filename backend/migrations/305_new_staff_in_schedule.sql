-- 305_new_staff_in_schedule.sql — новий співробітник одразу у складі графіка
--
-- ЩО СКАЗАВ ВЛАСНИК (16.09): «додав нового співробітника, але він не зʼявився,
-- щоб додати його в графік — зроби, щоб автоматом зʼявлявся в персоналі графіка
-- і я міг там керувати всім».
--
-- ЩО БУЛО НАСПРАВДІ (перевірено фактом у БД):
--   • «Даша» (users #67, 16.09 09:20) заведена з роллю «Адмін» → картки в masters
--     НЕ створилось узагалі (код заводив картку лише для ролі 'master'),
--     тому в «Персоналі графіка» її не було навіть у списку «можна додати».
--   • Міграція 298 проставила in_schedule ОДНОРАЗОВО наявним людям. Колонка не мала
--     DEFAULT, тож будь-яка нова картка отримувала NULL → COALESCE(...,false) →
--     людина мовчки опинялась поза графіком.
--
-- ЩО РОБИМО ТУТ: DEFAULT true на рівні БД. Це закриває ВСІ п'ять місць, де
-- створюється картка (users.js, employees.js, admin.js, migrate.js, signup-finalize.js),
-- а не одне — інакше завтра з'явиться шостий шлях і баг повернеться.
-- Звільнених і неактивних не чіпаємо (у них явний false з 298).

ALTER TABLE masters ALTER COLUMN in_schedule SET DEFAULT true;

-- Підбираємо «загублених»: активні працюючі картки, яким ніхто не проставив прапорець.
UPDATE masters
   SET in_schedule = true
 WHERE in_schedule IS NULL
   AND COALESCE(active, true) = true
   AND COALESCE(status, 'active') <> 'fired'
   AND merged_into IS NULL;
